// Rasterizes Natural Earth land polygons (via world-atlas) into a land/water grid.
const topo = require('topojson-client');
const fs = require('fs');
const land = require('world-atlas/land-50m.json');
const geo = topo.feature(land, land.objects.land);
const W = 500, LAT_TOP = 80, LAT_BOT = -58;
const STEP = 360 / W; const H = Math.round((LAT_TOP - LAT_BOT) / STEP);
const polys = [];
for (const f of geo.features) {
  const g = f.geometry; const list = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const p0 of list) {
    // unwrap rings that cross the antimeridian so longitudes are continuous
    const p = p0.map(r => { let off=0, prev=r[0][0]; return r.map(([x,y]) => { if (x-prev>180) off-=360; else if (prev-x>180) off+=360; prev=x; return [x+off,y]; }); });
    let minx=1e9,maxx=-1e9,miny=1e9,maxy=-1e9;
    for (const [x,y] of p[0]) { minx=Math.min(minx,x);maxx=Math.max(maxx,x);miny=Math.min(miny,y);maxy=Math.max(maxy,y); }
    polys.push({ rings: p, minx, maxx, miny, maxy });
  }
}
function inRing(x, y, r) { let c = false; for (let i=0,j=r.length-1;i<r.length;j=i++){ const [xi,yi]=r[i],[xj,yj]=r[j]; if(((yi>y)!==(yj>y)) && (x < (xj-xi)*(y-yi)/(yj-yi)+xi)) c=!c; } return c; }
function isLand(x0, y) {
  for (const x of [x0, x0+360, x0-360])
  for (const p of polys) { if (x<p.minx||x>p.maxx||y<p.miny||y>p.maxy) continue;
    if (inRing(x,y,p.rings[0])) { let hole=false; for (let k=1;k<p.rings.length;k++) if (inRing(x,y,p.rings[k])) {hole=true;break;} if(!hole) return true; } }
  return false;
}
const grid = new Uint8Array(W*H);
for (let ty=0; ty<H; ty++) for (let tx=0; tx<W; tx++) {
  // sample 5 points, land if >=2 hit (keeps small islands visible)
  const lon=-180+(tx+0.5)*STEP, lat=LAT_TOP-(ty+0.5)*STEP; const d=STEP*0.3;
  let n=0; for (const [ox,oy] of [[0,0],[d,d],[-d,d],[d,-d],[-d,-d]]) if (isLand(lon+ox,lat+oy)) n++;
  grid[ty*W+tx] = n>=2 ? 1 : 0;
}
// RLE encode
let out=[], cur=grid[0], run=0;
for (const v of grid) { if (v===cur) run++; else { out.push(run); cur=v; run=1; } } out.push(run);
const land_n = grid.reduce((a,b)=>a+b,0);
fs.writeFileSync(__dirname+'/../public/shared/mapdata.js', `// Generated by tools/buildmap.cjs from Natural Earth (public domain)\nexport const MAP_W=${W}, MAP_H=${H}, MAP_LAT_TOP=${LAT_TOP}, MAP_STEP=${STEP};\nexport const MAP_RLE=[${out.join(',')}]; // starts with water\nexport const MAP_FIRST=${grid[0]};\n`);
console.log(W,H,'land tiles',land_n, 'rle len', out.length);
