// Rasterizes Natural Earth country shapes (via world-atlas) onto the game map, so each land tile
// knows which real-world country it sits in. Tiny countries that cover only a few tiles are
// folded into their neighbours. Writes public/shared/regiondata.js.
import { createRequire } from 'module';
import { writeFileSync } from 'fs';
import { getLand, MAP_W as W, MAP_H as H, MAP_LAT_TOP as LAT_TOP, MAP_STEP as STEP } from '../public/shared/map.js';
const require = createRequire(import.meta.url);
const topo = require('topojson-client');
const world = require('world-atlas/countries-50m.json');
const geo = topo.feature(world, world.objects.countries);
const MIN_TILES = 8;

const countries = [];
for (const f of geo.features) {
  const g = f.geometry; if (!g) continue;
  const list = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  const polys = [];
  for (const p0 of list) {
    const p = p0.map(r => { let off = 0, prev = r[0][0]; return r.map(([x, y]) => { if (x - prev > 180) off -= 360; else if (prev - x > 180) off += 360; prev = x; return [x + off, y]; }); });
    let minx = 1e9, maxx = -1e9, miny = 1e9, maxy = -1e9;
    for (const [x, y] of p[0]) { minx = Math.min(minx, x); maxx = Math.max(maxx, x); miny = Math.min(miny, y); maxy = Math.max(maxy, y); }
    polys.push({ rings: p, minx, maxx, miny, maxy });
  }
  countries.push({ name: f.properties.name, polys });
}
function inRing(x, y, r) { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if (((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi)) c = !c; } return c; }
function countryAt(x0, y) {
  for (const x of [x0, x0 + 360, x0 - 360]) for (let k = 0; k < countries.length; k++) for (const p of countries[k].polys) {
    if (x < p.minx || x > p.maxx || y < p.miny || y > p.maxy) continue;
    if (inRing(x, y, p.rings[0]) && !p.rings.slice(1).some(r => inRing(x, y, r))) return k;
  }
  return -1;
}
const land = getLand(), N = W * H, reg = new Int16Array(N).fill(-1);
for (let ty = 0; ty < H; ty++) for (let tx = 0; tx < W; tx++) {
  const i = ty * W + tx; if (!land[i]) continue;
  const lon = -180 + (tx + 0.5) * STEP, lat = LAT_TOP - (ty + 0.5) * STEP, d = STEP * 0.3;
  const votes = new Map();
  for (const [ox, oy] of [[0, 0], [d, d], [-d, d], [d, -d], [-d, -d]]) { const k = countryAt(lon + ox, lat + oy); if (k >= 0) votes.set(k, (votes.get(k) || 0) + 1); }
  let best = -1, bv = 0; for (const [k, v] of votes) if (v > bv) { bv = v; best = k; }
  reg[i] = best;
}
// fill land with no country (coast slivers) and countries too small to matter from their neighbours
function grow() {
  let changed = true;
  while (changed) {
    changed = false;
    for (let i = 0; i < N; i++) {
      if (!land[i] || reg[i] >= 0) continue;
      const x = i % W;
      for (const n of [x > 0 ? i - 1 : -1, x < W - 1 ? i + 1 : -1, i - W, i + W]) if (n >= 0 && n < N && reg[n] >= 0) { reg[i] = reg[n]; changed = true; break; }
    }
  }
}
grow();
const count = new Map(); for (const r of reg) if (r >= 0) count.set(r, (count.get(r) || 0) + 1);
for (let i = 0; i < N; i++) if (reg[i] >= 0 && count.get(reg[i]) < MIN_TILES) reg[i] = -1;
grow();
// islands that never touched a country (e.g. remote specks): leave them out of any region
// renumber, biggest first
const sizes = new Map(); for (const r of reg) if (r >= 0) sizes.set(r, (sizes.get(r) || 0) + 1);
const order = [...sizes.keys()].sort((a, b) => sizes.get(b) - sizes.get(a));
const remap = new Map(order.map((k, j) => [k, j]));
const names = order.map(k => countries[k].name);
const out = []; let cur = -2, run = 0;
for (let i = 0; i < N; i++) { const v = reg[i] >= 0 ? remap.get(reg[i]) : -1; if (v === cur) run++; else { if (run) out.push(cur, run); cur = v; run = 1; } }
out.push(cur, run);
writeFileSync(new URL('../public/shared/regiondata.js', import.meta.url),
  `// Generated by tools/buildregions.mjs from Natural Earth (public domain)\nexport const REGION_NAMES=${JSON.stringify(names)};\nexport const REGION_RLE=[${out.join(',')}]; // pairs of region id (-1 none), run length\n`);
console.log(names.length, 'countries;', 'biggest', names.slice(0, 5).map((n, j) => n + ':' + sizes.get(order[j])).join(' '), '; smallest', names.at(-1) + ':' + sizes.get(order.at(-1)));
